<?php

use App\Exceptions\CodeUsedUpException;
use App\Jobs\GenerateCodeBatch;
use App\Models\ActivationCode;
use App\Models\Category;
use App\Models\Level;
use App\Models\Subscription;
use App\Models\User;
use App\Services\ActivationCodeService;
use App\Services\DeviceService;
use App\Services\SubscriptionService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Queue;

uses(RefreshDatabase::class);

const CODE_DEVICE = '55555555-5555-4555-8555-555555555555';

beforeEach(function () {
    $this->level = Level::factory()->create();
    $this->category = Category::factory()->for($this->level)->create(['is_free' => false]);
    $this->student = User::factory()->student()->create(['level_id' => $this->level->id]);
    app(DeviceService::class)->bind($this->student, CODE_DEVICE);
    $this->redeem = fn (string $code, ?User $as = null) => $this->actingAs($as ?? $this->student, 'sanctum')
        ->withHeader('X-Device-Id', CODE_DEVICE)
        ->postJson('/api/v1/codes/redeem', ['code' => $code]);
});

function studentOn(Level $level): User
{
    $student = User::factory()->student()->create(['level_id' => $level->id]);
    app(DeviceService::class)->bind($student, CODE_DEVICE);

    return $student;
}

it('generates unique codes from the safe alphabet', function () {
    $batch = app(ActivationCodeService::class)->generate($this->category, 50, 1, null, null);

    $codes = ActivationCode::where('batch_id', $batch)->pluck('code');
    expect($codes)->toHaveCount(50)
        ->and($codes->unique())->toHaveCount(50)
        ->and($codes->every(fn ($code) => preg_match('/^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{10}$/', $code) === 1))->toBeTrue();
});

it('large batches are generated by a queued job', function () {
    Queue::fake();

    app(ActivationCodeService::class)->generate($this->category, 500, 1, null, null);

    Queue::assertPushed(GenerateCodeBatch::class);
});

it('redeem grants category subscription', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 1, 'ends_at' => now()->addMonth()]);

    ($this->redeem)($code->code)->assertOk()
        ->assertJsonPath('data.category.id', $this->category->id)
        ->assertJsonPath('data.category.is_subscribed', true);

    $subscription = Subscription::where('user_id', $this->student->id)->first();
    expect($subscription->ends_at->toDateString())->toBe(now()->addMonth()->toDateString())
        ->and($subscription->code_redemption_id)->not->toBeNull()
        ->and($code->fresh()->uses_count)->toBe(1);
});

it('redeem is case insensitive and trims', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['code' => 'ABCDEFGH23', 'max_uses' => 1]);

    ($this->redeem)('  abcdefgh23 ')->assertOk();
});

it('unknown code is invalid', function () {
    ($this->redeem)('ZZZZZZZZZZ')->assertStatus(422)->assertJsonPath('code', 'code_invalid');
});

it('expired code is rejected', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 1, 'expires_at' => now()->subMinute()]);

    ($this->redeem)($code->code)->assertStatus(422)->assertJsonPath('code', 'code_expired');
});

it('used up code is rejected', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 1, 'uses_count' => 1]);

    ($this->redeem)($code->code)->assertStatus(422)->assertJsonPath('code', 'code_used_up');
});

it('last use goes to exactly one student', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 2, 'uses_count' => 1]);
    $other = studentOn($this->level);

    ($this->redeem)($code->code)->assertOk();
    app('auth')->forgetGuards();
    ($this->redeem)($code->code, $other)->assertStatus(422)->assertJsonPath('code', 'code_used_up');

    expect($code->fresh()->uses_count)->toBe(2)
        ->and(Subscription::count())->toBe(1);
});

it('uses the guarded increment so a lost race cannot overspend', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 1, 'uses_count' => 0]);
    // Another request wins the race between our read and our write.
    ActivationCode::whereKey($code->id)->update(['uses_count' => 1]);

    expect(fn () => app(ActivationCodeService::class)->consume($code))->toThrow(CodeUsedUpException::class);
    expect($code->fresh()->uses_count)->toBe(1);
});

it('same student cannot redeem the same code twice', function () {
    $code = ActivationCode::factory()->for($this->category)->create(['max_uses' => 5]);

    ($this->redeem)($code->code)->assertOk();
    ($this->redeem)($code->code)->assertStatus(422)->assertJsonPath('code', 'code_invalid');

    expect($code->fresh()->uses_count)->toBe(1);
});

it('code of another level is invalid', function () {
    $otherCategory = Category::factory()->create();
    $code = ActivationCode::factory()->for($otherCategory)->create(['max_uses' => 1]);

    ($this->redeem)($code->code)->assertStatus(422)->assertJsonPath('code', 'code_invalid');
    expect($code->fresh()->uses_count)->toBe(0);
});

it('granting again keeps the later end date', function () {
    $service = app(SubscriptionService::class);
    $service->grant($this->student, $this->category, now()->addMonths(3), null, null);
    $service->grant($this->student, $this->category, now()->addMonth(), null, null);

    expect(Subscription::count())->toBe(1)
        ->and(Subscription::first()->ends_at->toDateString())->toBe(now()->addMonths(3)->toDateString());

    $service->grant($this->student, $this->category, null, null, null);
    expect(Subscription::first()->ends_at)->toBeNull();
});

it('lists my subscriptions', function () {
    app(SubscriptionService::class)->grant($this->student, $this->category, null, null, null);

    $this->actingAs($this->student, 'sanctum')->withHeader('X-Device-Id', CODE_DEVICE)
        ->getJson('/api/v1/subscriptions')->assertOk()
        ->assertJsonPath('data.0.category.id', $this->category->id)
        ->assertJsonPath('data.0.ends_at', null)
        ->assertJsonStructure(['data' => [['category' => ['id', 'name'], 'starts_at', 'ends_at']]]);
});

it('redeem is throttled', function () {
    foreach (range(1, 10) as $i) {
        ($this->redeem)('WRONGCODE'.$i);
    }

    ($this->redeem)('WRONGCODE11')->assertStatus(429);
});
